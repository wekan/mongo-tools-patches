#!/bin/bash
#
# multicall.sh - generate ONE mongo-tools program that is all eight tools.
#
#   Usage (in the upstream tree apply-patches.sh prepared):
#     bash <patches>/releases/multicall.sh
#   Then:
#     go build -ldflags "$(bash <patches>/releases/multicall.sh --ldflags VER COMMIT)" ./wekan_multicall
#
# WHY. Each of the eight tools is its own Go program, and each carries its own
# copy of the Go runtime, the MongoDB driver and the tools' common packages:
# 8 binaries of 8-14 MB, ~105 MB in every WeKan bundle, image and snap. Built
# as one program they share all of it.
#
# HOW. Upstream's <tool>/main/*.go are `package main` with `func main()` and the
# VersionStr / GitCommit variables the linker sets. Those files are copied
# unchanged in substance into wekan_multicall/tools/<tool>/, as `package
# <tool>main` with `func Main()`, and wekan_multicall/main.go picks one:
#   - by the name it was run as (argv[0]): mongodump, mongodump.exe, or
#     mongodump-<arch> - so a symlink or hard link named after a tool IS that
#     tool, exactly as before;
#   - or by its first argument: `mongo-tools mongodump --help` - which the
#     Windows .cmd shims use, since Windows has no symlinks to rely on.
# Each tool then sees os.Args as if it had been run on its own, so its option
# parsing, --help and --version are unchanged.
#
# Nothing upstream is edited: the generated directory is new, and the per-tool
# builds from ./<tool>/main are unaffected.

set -euo pipefail

TOOLS="bsondump mongodump mongoexport mongofiles mongoimport mongorestore mongostat mongotop"
MODULE="github.com/mongodb/mongo-tools"
DIR="wekan_multicall"

if [ "${1:-}" = "--ldflags" ]; then
  ver="${2:?--ldflags VERSION COMMIT}"; commit="${3:?--ldflags VERSION COMMIT}"
  flags="-s -w"
  for t in $TOOLS; do
    flags="$flags -X $MODULE/$DIR/tools/$t.VersionStr=$ver -X $MODULE/$DIR/tools/$t.GitCommit=$commit"
  done
  printf '%s\n' "$flags"
  exit 0
fi

[ -f go.mod ] && grep -q "^module $MODULE\$" go.mod \
  || { echo "multicall.sh: run it at the root of the mongo-tools tree" >&2; exit 1; }

rm -rf "$DIR"
mkdir -p "$DIR/tools"
for t in $TOOLS; do
  src="$t/main"
  [ -d "$src" ] || { echo "multicall.sh: $src is missing upstream" >&2; exit 1; }
  dst="$DIR/tools/$t"
  mkdir -p "$dst"
  for f in "$src"/*.go; do
    case "$f" in *_test.go) continue ;; esac
    # Exactly one `package main` and at most one `func main()` per file, or the
    # rewrite would be guessing: fail instead.
    [ "$(grep -c '^package main$' "$f")" -eq 1 ] || { echo "multicall.sh: $f has no single 'package main'" >&2; exit 1; }
    [ "$(grep -c '^func main() {$' "$f")" -le 1 ] || { echo "multicall.sh: $f has more than one main()" >&2; exit 1; }
    sed -e "s/^package main\$/package ${t}main/" -e 's/^func main() {$/func Main() {/' "$f" > "$dst/$(basename "$f")"
  done
  grep -q '^func Main() {$' "$dst"/*.go || { echo "multicall.sh: $t has no main() to export" >&2; exit 1; }
done

{
  cat <<'EOF'
// Code generated by wekan/mongo-tools-patches releases/multicall.sh. DO NOT EDIT.

// Package main is all of the MongoDB Database Tools in one program. It runs the
// tool it is named after (argv[0]: mongodump, mongodump.exe, mongodump-amd64),
// or the tool named by its first argument (mongo-tools mongodump ...).
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

EOF
  for t in $TOOLS; do printf '\t%s "%s/%s/tools/%s"\n' "${t}main" "$MODULE" "$DIR" "$t"; done
  cat <<'EOF'
)

var tools = map[string]func(){
EOF
  for t in $TOOLS; do printf '\t"%s": %smain.Main,\n' "$t" "$t"; done
  cat <<'EOF'
}

// toolName is the tool a program name stands for: its base name without .exe,
// and without a -<platform> suffix, which is how the release assets are named.
func toolName(arg0 string) string {
	name := strings.TrimSuffix(strings.ToLower(filepath.Base(arg0)), ".exe")
	if _, ok := tools[name]; ok {
		return name
	}
	for t := range tools {
		if strings.HasPrefix(name, t+"-") {
			return t
		}
	}
	return ""
}

func usage() {
	names := make([]string, 0, len(tools))
	for t := range tools {
		names = append(names, t)
	}
	sort.Strings(names)
	fmt.Fprintf(os.Stderr, "usage: mongo-tools <tool> [options]\n   or: run it as one of: %s\n", strings.Join(names, ", "))
}

func main() {
	if t := toolName(os.Args[0]); t != "" {
		tools[t]()
		return
	}
	if len(os.Args) > 1 {
		if run, ok := tools[os.Args[1]]; ok {
			// The tool sees itself as having been run on its own.
			os.Args = append([]string{os.Args[1]}, os.Args[2:]...)
			run()
			return
		}
	}
	usage()
	os.Exit(2)
}
EOF
} > "$DIR/main.go"

echo "multicall.sh: $DIR/ generated for: $TOOLS"
